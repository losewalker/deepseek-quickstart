--  产品信息表 (products)
CREATE TABLE products (
    product_id SERIAL PRIMARY KEY,
    sku VARCHAR(20) UNIQUE NOT NULL,
    product_name VARCHAR(100) NOT NULL,
    version VARCHAR(20) NOT NULL,  -- 普通版/安心版
    volume VARCHAR(10) NOT NULL,    -- 30ml/50ml
    record_number VARCHAR(20) NOT NULL,
    base_price NUMERIC(8,2) NOT NULL,
    cost_price NUMERIC(8,2) NOT NULL,
    applicable_skin_types TEXT NOT NULL,
    shelf_life_unopened INT NOT NULL,  -- 年
    shelf_life_opened INT NOT NULL,    -- 月
    technology_features TEXT NOT NULL,
    usage_precautions TEXT NOT NULL
);

-- 产品成分表 (product_ingredients)
CREATE TABLE ingredients (
    ingredient_id SERIAL PRIMARY KEY,
    product_id INT REFERENCES products(product_id),
    ingredient_name VARCHAR(50) NOT NULL,
    concentration VARCHAR(20),
    function TEXT NOT NULL,
    source VARCHAR(50) NOT NULL
);

-- 产品库存表 (inventory)
CREATE TABLE inventory (
    inventory_id SERIAL PRIMARY KEY,
    product_id INT REFERENCES products(product_id),
    batch_number VARCHAR(10) NOT NULL,
    production_date DATE NOT NULL,
    expiry_date DATE NOT NULL,
    warehouse VARCHAR(50) NOT NULL,
    current_stock INT NOT NULL,
    min_stock_alert INT NOT NULL
);


